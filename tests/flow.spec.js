 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Nome completo').fill('Gerente navegador '+suffix);
 await dialog.getByLabel('E-mail',{exact:false}).fill(email);await dialog.getByLabel('Telefone',{exact:false}).fill('11999999999');
 await dialog.getByLabel('Senha inicial / nova senha',{exact:false}).fill(password);
 await dialog.getByLabel('Cargo').selectOption('GERENTE');
 const units=await dialog.getByLabel('Unidades do gerente').locator('option').allTextContents();
